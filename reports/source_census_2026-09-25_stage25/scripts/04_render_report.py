    link_named = f"{link['model_name']}: " + ("да" if link["exact"] else ("маска " + link["family_mask"][0]) if link["family_mask"] else "нет")
    return (f"| {card['category']} | {card['article']} | {doc['file'][:42]} (метка в имени: {doc['language_hint'] or '—'}) | {yes(f['russian_by_text'])}"
            f"{' (язык по тексту: ' + ', '.join(f['languages_by_text']) + ')' if f['languages_by_text'] else ''} | {f['tied_by_official_page']} | {named} | {link_named} | {LABELS[doc['rule4_analog']]} |")


